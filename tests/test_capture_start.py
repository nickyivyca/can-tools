"""A capture's start in the format layer (``logio.capture_start``, ``CaptureStart``):
BUSMASTER, app-style and PEAK-style TRC, candump and Vector ASC, and the readers built
on it (``logio.busmaster_start``, ``peak_trc.start_time``).

Every fixture is synthetic, written inside the test.

Run standalone:   python tests/test_capture_start.py
Or under pytest:  python -m pytest tests/test_capture_start.py
"""
import calendar
import sys
import tempfile
from datetime import datetime, timedelta, timezone
from pathlib import Path
from zoneinfo import ZoneInfo

import can

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from canbench import logio  # noqa: E402
from canbench.parsers.peak_trc import first_offset, start_local, start_time  # noqa: E402
from canbench.trcwriter import TRCWriter  # noqa: E402

LA = ZoneInfo("America/Los_Angeles")


def _write(text, name):
    p = Path(tempfile.mkdtemp(prefix="canbench-start-")) / name
    p.write_text(text, encoding="utf-8")
    return p


def _bm(header_time):
    return f"""***BUSMASTER Ver 3.2.2***
***PROTOCOL CAN***
***[START LOGGING SESSION]***
***START DATE AND TIME {header_time}***
***HEX***
***<Time><Tx/Rx><Channel><CAN ID><Type><DLC><DataBytes>***
16:51:58:0000 Rx 1 0x308 s 2 01 02
"""


def _old_busmaster_start(dd, mo, yy, hh, mi, ss, ms):
    """The formula logio.busmaster_start used before the format layer had a start."""
    return calendar.timegm((yy, mo, dd, hh, mi, ss)) + ms / 1000.0


def test_busmaster_header_is_local():
    p = _write(_bm("12:02:2025 16:51:57:846"), "a.log")
    st = logio.capture_start(p)
    assert st.basis == "local" and st.zone is None
    assert st.wall == datetime(2025, 2, 12, 16, 51, 57, 846000)
    assert st.seconds == _old_busmaster_start(12, 2, 2025, 16, 51, 57, 846)
    assert logio.busmaster_start(p) == st.seconds
    # 2025-02-12 is PST (UTC-8): the instant is 8 h after the digits read as UTC
    assert st.instant_ns(LA) == (calendar.timegm((2025, 2, 13, 0, 51, 57)) * 10**9 + 846_000_000)
    assert st.instant_ns("America/Los_Angeles") == st.instant_ns(LA)
    try:
        st.instant_ns()
    except ValueError:
        pass
    else:
        raise AssertionError("a local start must need a zone")


def test_busmaster_unpadded_header():
    """BUSMASTER does not zero-pad: "12:2:2025 16:51:57:846", "17:1:2026 0:1:30:217"."""
    p = _write(_bm("17:1:2026 0:1:30:217"), "a.log")
    st = logio.capture_start(p)
    assert st.wall == datetime(2026, 1, 17, 0, 1, 30, 217000)
    assert logio.busmaster_start(p) == _old_busmaster_start(17, 1, 2026, 0, 1, 30, 217)


def test_busmaster_bad_or_missing_header():
    assert logio.capture_start(_write(_bm("31:02:2025 10:00:00:000"), "a.log")) is None
    text = _bm("x").replace("***START DATE AND TIME x***\n", "")
    p = _write(text, "a.log")
    assert logio.capture_start(p) is None and logio.busmaster_start(p) is None


def _app_trc(name, t0, zone="America/Los_Angeles", frames=((0.0, 0x308),)):
    p = Path(tempfile.mkdtemp(prefix="canbench-start-")) / name
    with TRCWriter(str(p), zone=zone) as w:
        for dt, aid in frames:
            w.on_message_received(can.Message(timestamp=t0 + dt, arbitration_id=aid,
                                              data=b"\x01\x02", is_extended_id=False, channel=0))
    return p


def test_app_trc_is_utc_with_zone():
    t0 = 1794586450.697
    p = _app_trc("coda_20261113_085410_T0.trc", t0)
    st = logio.capture_start(p)
    assert st.basis == "utc" and st.zone == "America/Los_Angeles"
    assert abs(st.seconds - t0) < 1e-3 and st.seconds == start_time(p)
    assert abs(st.instant_ns() / 1e9 - t0) < 1e-3
    assert st.instant_ns(LA) == st.instant_ns()          # a utc start is never shifted
    when, zone = start_local(p)
    assert abs(when.timestamp() - st.instant()) < 1e-3


def test_app_trc_without_zone_name_is_still_utc():
    p = _app_trc("t.trc", 1794586450.0, zone=None)
    text = p.read_text(encoding="utf-8")
    lines = [ln if "Start time (local)" not in ln else ln.split(" America/")[0].split(" Etc/")[0]
             for ln in text.splitlines()]
    p.write_text("\n".join(lines) + "\n", encoding="utf-8")
    st = logio.capture_start(p)
    assert st.basis == "utc" and st.zone is None


PEAK_TRC = """;$FILEVERSION=2.1
;$STARTTIME=45000.25
;$COLUMNS=N,O,T,B,I,d,R,L,D
;
;   Start time: 15.03.2023 06:00:00.000.0
;   Generated by PCAN-View v5.0.0.814
;-------------------------------------------------------------------------------
       1       100.000 DT 1     0308 Rx - 2    01 02
"""


def test_peak_trc_is_local():
    p = _write(PEAK_TRC, "t.trc")
    st = logio.capture_start(p)
    assert st.basis == "local" and st.zone is None
    assert st.wall == datetime(2023, 3, 15, 6, 0, 0)
    assert st.seconds == (45000.25 - 25569) * 86400.0 == start_time(p)
    # 2023-03-15 is PDT (UTC-7)
    assert st.instant_ns(LA) == calendar.timegm((2023, 3, 15, 13, 0, 0)) * 10**9


def test_trc_first_offset():
    p = _write(PEAK_TRC.replace("       1       100.000 DT 1     0308 Rx - 2    01 02\n",
                                "       1       100.000 ER 1        - Rx - 5    04 01 0A 00 00\n"
                                "       2       102.500 DT 1     0308 Rx - 2    01 02\n"), "t.trc")
    assert first_offset(p) == 0.1                     # the ER line is t=0, as in parse_file
    from canbench.parsers import parse_file
    assert [round(f.timestamp, 6) for f in parse_file(p)] == [0.0025]
    assert first_offset(_write(PEAK_TRC.split("       1 ")[0], "e.trc")) is None


def test_candump_first_frame_is_utc():
    p = _write("(1794586450.697123) can0 308#0102\n(1794586451.000000) can1 001#00\n", "c.log")
    st = logio.capture_start(p)
    assert st.basis == "utc" and st.seconds == 1794586450.697123
    assert st.wall == datetime(1970, 1, 1) + timedelta(seconds=1794586450, microseconds=697123)
    assert st.instant_ns() == 1794586450_697123000
    assert logio.busmaster_start(p) is None


def test_vector_asc_date_is_local():
    body = "base hex  timestamps absolute\nno internal events logged\n" \
           "   0.0100 1  308  Rx  d 2 01 02\n"
    for line, want in (("date Sat Mar 08 04:14:24 PM 2025", datetime(2025, 3, 8, 16, 14, 24)),
                       ("date Sat Mar  8 04:14:24.250 pm 2025", datetime(2025, 3, 8, 16, 14, 24, 250000)),
                       ("date Mon Sep 15 10:21:43.512 2025", datetime(2025, 9, 15, 10, 21, 43, 512000)),
                       ("date Mon Sep 15 10:21:43 2025", datetime(2025, 9, 15, 10, 21, 43))):
        st = logio.capture_start(_write(line + "\n" + body, "v.asc"))
        assert st is not None, line
        assert st.basis == "local" and st.wall == want, (line, st)
        assert st.seconds == calendar.timegm(want.timetuple()[:6]) + want.microsecond / 1e6
    assert logio.capture_start(_write("date Montag 15 Sep\n" + body, "v.asc")) is None


def test_formats_without_a_start():
    savvy = "Time Stamp,ID,Extended,Dir,Bus,LEN,D1,D2\n100,00000308,false,Rx,0,2,01,02\n"
    assert logio.capture_start(_write(savvy, "s.csv")) is None
    assert logio.capture_start(_write("not a capture\n", "x.txt")) is None


def test_utc_instant_ignores_zone():
    p = _write("(1700000000.500000) can0 308#0102\n(1700000000.600000) can0 308#0102\n", "c.log")
    st = logio.capture_start(p)
    assert st.instant_ns(timezone(timedelta(hours=5))) == 1700000000_500000000



"""PEAK TRC 2.1 writer that keeps error frames, remote frames and CAN FD.

python-can's ``TRCWriter`` (4.6.1) drops error frames, remote frames and CAN FD
frames with a warning. This writer writes all of them, in the column layout of
PEAK's 2.1 specification (``N,O,T,B,I,d,R,L,D``):

* data frames as ``DT``, CAN FD as ``FD`` / ``FB`` / ``FE`` / ``BI``, remote
  frames as ``RR``;
* each error frame (Linux ``can/error.h`` layout, see ``canbench.errors``) as the
  ``ER`` / ``ST`` / ``EC`` records it amounts to, followed by an ``EV`` line that
  holds what the adapter itself reported::

      EV 1 canbench-raw pcan id=00000004 data=00 07 0A 00 status=...

  so a reader can always recover the source, whatever the mapping did.

Bus numbers are the channel's number plus one (``can0`` -> bus 1), as python-can
writes them; ``canbench.logio.read_messages`` maps them back. Offsets are
milliseconds from the first message.

**Start time (owner ruling 2026-11-13: "lets go with UTC").** ``$STARTTIME`` is
UTC, as python-can writes it, in can-tools and in the Android loggers alike. PEAK's
own recorders write local time there (their spec), so the header also says which
it is, in two comment lines that :func:`canbench.parsers.peak_trc.start_local`
reads::

    ;   Start time (UTC): 2026-11-13T16:54:10.697+00:00
    ;   Start time (local): 2026-11-13T08:54:10.697-08:00 America/Los_Angeles

The local line is ISO 8601 with its UTC offset, then the IANA zone name when it
is known (left off otherwise), so a capture made in another time zone says so.

``canbench.logio.open_writer`` returns this writer for ``.trc`` paths.
"""
from __future__ import annotations

import os
from datetime import datetime, timedelta, timezone
from typing import Any

import can
from can.io.generic import TextIOMessageWriter
from can.util import channel2int, len2dlc

from canbench import errors

_OLE_EPOCH = datetime(1899, 12, 30, tzinfo=timezone.utc)

_HEADER = """;$FILEVERSION=2.1
;$STARTTIME={start_days}
;$COLUMNS=N,O,T,B,I,d,R,L,D
;
;   {path}
;
;   Start time (UTC): {start}
;   Start time (local): {local}
;   Generated by canbench TRCWriter (error frames as ER/ST/EC records, adapter report as EV)
;-------------------------------------------------------------------------------
;   Message   Time    Type    ID     Rx/Tx
;   Number    Offset  |  Bus  [hex]  |  Reserved
;   |         [ms]    |  |    |      |  |  Data Length Code
;   |         |       |  |    |      |  |  |    Data [hex] ...
;   |         |       |  |    |      |  |  |    |
;---+-- ------+------ +- +- --+----- +- +- +--- +- -- -- -- -- -- -- --
"""


def local_zone() -> str | None:
    """IANA name of this machine's time zone, or None if it cannot be told: ``$TZ`` when it
    names a zone, else the ``/etc/localtime`` link (Linux). Windows gives None."""
    tz = os.environ.get("TZ", "").lstrip(":")
    if "/" in tz and not tz.startswith("/"):
        return tz
    try:
        target = os.path.realpath("/etc/localtime")
    except OSError:
        return None
    marker = "/zoneinfo/"
    return target.split(marker, 1)[1] if marker in target else None


def local_start_text(ts: float, zone: str | None = None) -> str:
    """``2026-11-13T08:54:10.697-08:00 America/Los_Angeles``: the start in local time with its
    offset, and the zone name when known. ``zone`` overrides the machine's zone."""
    name = zone or local_zone()
    tzinfo = None
    if name:
        try:
            from zoneinfo import ZoneInfo
            tzinfo = ZoneInfo(name)
        except Exception:
            name, tzinfo = None, None
    local = datetime.fromtimestamp(ts, tzinfo) if tzinfo else datetime.fromtimestamp(ts).astimezone()
    text = local.isoformat(timespec="milliseconds")
    return f"{text} {name}" if name else text


def _hex(data: bytes) -> str:
    return " ".join(f"{b:02X}" for b in data)


def raw_text(msg: can.Message) -> str:
    """The EV text recording what the adapter reported for an error frame."""
    backend = getattr(msg, "raw_backend", "") or "linux"
    raw_id = getattr(msg, "raw_id", None)
    raw_data = getattr(msg, "raw_data", None)
    if not getattr(msg, "raw_backend", ""):
        raw_id, raw_data = msg.arbitration_id, bytes(msg.data)
    text = f"canbench-raw {backend} id={raw_id:08X} data={_hex(raw_data) or '-'}"
    note = getattr(msg, "raw_note", "")
    if note:
        text += " " + note
    if getattr(msg, "raw_backend", ""):
        text += f" linux={msg.arbitration_id:08X}:{_hex(bytes(msg.data))}"
    return text


class TRCWriter(TextIOMessageWriter):
    """Write ``can.Message`` objects to a PEAK TRC 2.1 file (see module doc)."""

    def __init__(self, file: Any, channel: int = 1, zone: str | None = None, **kwargs: Any) -> None:
        """``zone``: IANA name of the local time zone for the start-time comment (default:
        the machine's, see :func:`local_zone`)."""
        super().__init__(file, mode="w")
        self.zone = zone
        if hasattr(self.file, "reconfigure"):
            self.file.reconfigure(newline="\r\n")
        self.channel = channel
        self.msgnr = 0
        self.first_timestamp: float | None = None
        self.counts = {"frames": 0, "errors": 0, "records": 0}

    def _bus(self, msg: can.Message) -> int:
        ch = channel2int(msg.channel)
        return self.channel if ch is None else ch + 1

    def _header(self, ts: float) -> None:
        start = datetime.fromtimestamp(ts, timezone.utc)
        name = getattr(self.file, "name", "") or ""
        path = os.path.abspath(name) if isinstance(name, str) and name else ""
        self.file.write(_HEADER.format(start_days=(start - _OLE_EPOCH) / timedelta(days=1),
                                       path=path, start=start.isoformat(timespec="milliseconds"),
                                       local=local_start_text(ts, self.zone)))

    def _line(self, offset_ms: float, typ: str, bus: int, rest: str) -> None:
        self.msgnr += 1
        self.file.write(f"{self.msgnr:>7} {offset_ms:13.3f} {typ} {bus:>2} {rest}\n")

    def on_message_received(self, msg: can.Message) -> None:
        ts = msg.timestamp or 0.0
        if self.first_timestamp is None:
            self.first_timestamp = ts
            self._header(ts)
        off = (ts - self.first_timestamp) * 1000.0
        bus = self._bus(msg)
        d = "Rx" if msg.is_rx else "Tx"

        if msg.is_error_frame:
            self.counts["errors"] += 1
            report = errors.decode(msg)
            for typ, direction, data in errors.trc_records(report):
                self._line(off, typ, bus, f"{'-':>8} {direction} -  {len(data):<4} {_hex(data)}")
                self.counts["records"] += 1
            self._line(off, "EV", bus, raw_text(msg))
            return

        self.counts["frames"] += 1
        arb = f"{msg.arbitration_id:08X}" if msg.is_extended_id else f"{msg.arbitration_id:04X}"
        if msg.is_remote_frame:
            self._line(off, "RR", bus, f"{arb:>8} {d} -  {msg.dlc:<4}")
            return
        data = bytes(msg.data)
        if msg.is_fd:
            typ = {(False, False): "FD", (True, False): "FB", (False, True): "FE",
                   (True, True): "BI"}[(bool(msg.bitrate_switch), bool(msg.error_state_indicator))]
            dlc = len2dlc(len(data))
        else:
            typ, dlc = "DT", msg.dlc
        self._line(off, typ, bus, f"{arb:>8} {d} -  {dlc:<4} {_hex(data)}".rstrip())
